drop policy if exists "contacts read own profile" on public.contatos;
create policy "contacts read own profile" on public.contatos
for select to authenticated using (
  email_user = (select auth.jwt() ->> 'email')
  and exists (
    select 1 from public.perfil_estudo as profile
    where profile.id = contatos.perfil and profile.user_id = (select auth.uid())
  )
);

drop policy if exists "contacts create own profile" on public.contatos;
create policy "contacts create own profile" on public.contatos
for insert to authenticated with check (
  email_user = (select auth.jwt() ->> 'email')
  and exists (
    select 1 from public.perfil_estudo as profile
    where profile.id = contatos.perfil and profile.user_id = (select auth.uid())
  )
);

