-- O telefone do contato é um bigint com DDI + número, sem o sinal de +.
-- A conversão abaixo também corrige colunas antigas que tenham sido criadas como texto.
do $$
declare phone_type regtype;
begin
  select atttypid::regtype into phone_type
  from pg_attribute
  where attrelid = 'public.contatos'::regclass
    and attname = 'telefone'
    and not attisdropped;

  if phone_type is distinct from 'bigint'::regtype then
    execute $sql$
      alter table public.contatos
      alter column telefone type bigint
      using nullif(regexp_replace(telefone::text, '[^0-9]', '', 'g'), '')::bigint
    $sql$;
  end if;
end;
$$;

update public.contatos
set tipo = 5
where tipo is null or tipo not between 0 and 5;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.contatos'::regclass
      and conname = 'contatos_tipo_check'
  ) then
    alter table public.contatos add constraint contatos_tipo_check check (tipo between 0 and 5);
  end if;
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.contatos'::regclass
      and conname = 'contatos_telefone_check'
  ) then
    alter table public.contatos add constraint contatos_telefone_check check (telefone is null or telefone > 0);
  end if;
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.contatos'::regclass
      and conname = 'contatos_perfil_fkey'
  ) then
    alter table public.contatos add constraint contatos_perfil_fkey
      foreign key (perfil) references public.perfil_estudo(id) on delete cascade;
  end if;
end;
$$;

