-- Mantém os contatos alinhados caso o usuário altere o e-mail de autenticação.
create or replace function public.sync_auth_user_email()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_table text;
begin
  if new.email is distinct from old.email then
    update public.users
    set email = new.email, updated_at = now()
    where id = new.id;

    update public.perfil_estudo
    set email = new.email, updated_at = now()
    where user_id = new.id;

    -- Atualiza com segurança todas as tabelas do AKADEMO que usam
    -- email_user + perfil, inclusive professores e contatos, sem deixar
    -- de sincronizar módulos criados por migrações anteriores.
    for target_table in
      select relation.relname
      from pg_class as relation
      join pg_namespace as namespace on namespace.oid = relation.relnamespace
      where namespace.nspname = 'public'
        and relation.relkind = 'r'
        and exists (
          select 1 from pg_attribute
          where attrelid = relation.oid and attname = 'email_user' and not attisdropped
        )
        and exists (
          select 1 from pg_attribute
          where attrelid = relation.oid and attname = 'perfil' and not attisdropped
        )
        and exists (
          select 1 from pg_attribute
          where attrelid = relation.oid and attname = 'updated_at' and not attisdropped
        )
    loop
      execute format(
        'update public.%I as item set email_user = $1, updated_at = now() from public.perfil_estudo as profile where item.perfil = profile.id and profile.user_id = $2',
        target_table
      ) using new.email, new.id;
    end loop;
  end if;
  return new;
end;
$$;

